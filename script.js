let currentTable = 1;

let currentQuestion = null;


/* =========================================================
   HTML ELEMENTS
   ========================================================= */

const tableSelect =
    document.getElementById("tableSelect");

const tableTitle =
    document.getElementById("tableTitle");

const tableContainer =
    document.getElementById("tableContainer");


/* =========================================================
   DROPDOWN બનાવવું
   ========================================================= */

function loadSelector() {

    tableSelect.innerHTML = "";

    Object.keys(tables).forEach(function(number) {

        const option =
            document.createElement("option");

        option.value = number;

        option.textContent =
            tableNames[number] || `${number}નો ઘડિયો`;

        tableSelect.appendChild(option);

    });

}


/* =========================================================
   ઘડિયો SCREEN પર બતાવવો
   ========================================================= */

function displayTable(number) {

    currentTable = Number(number);

    const rows =
        tables[currentTable];

    tableTitle.textContent =
        tableNames[currentTable] ||
        `${currentTable}નો ઘડિયો`;

    tableContainer.innerHTML = "";


    rows.forEach(function(text, index) {

        const row =
            document.createElement("div");

        row.className =
            "table-row";


        /* Text */

        const textDiv =
            document.createElement("div");

        textDiv.className =
            "table-text";

        textDiv.textContent = text.display;


        /* Sound Button */

        const button =
            document.createElement("button");

        button.className =
            "sound-btn";

        button.textContent =
            "🔊";

        button.setAttribute(
            "aria-label",
            "ઘડિયો સાંભળો"
        );


        button.onclick = function() {

            speakGujarati(text.speak);

        };


        row.appendChild(textDiv);

        row.appendChild(button);

        tableContainer.appendChild(row);

    });

}


/* =========================================================
   ગુજરાતી VOICE
   ========================================================= */

function speakGujarati(text) {

    if (!("speechSynthesis" in window)) {

        alert(
            "તમારા Browserમાં Voice સુવિધા ઉપલબ્ધ નથી."
        );

        return;

    }


    /* પહેલાનો અવાજ બંધ */

    window.speechSynthesis.cancel();


    const speech =
        new SpeechSynthesisUtterance(text);


    /* Gujarati */

    speech.lang = "gu-IN";


    /*
       બાળકો માટે થોડો ધીમો અવાજ
    */

    speech.rate = 0.72;

    speech.pitch = 1;

    speech.volume = 1;


    window.speechSynthesis.speak(speech);

}


/* =========================================================
   આખો ઘડિયો સાંભળવો
   ========================================================= */

document
    .getElementById("playAllBtn")
    .addEventListener("click", function() {


        const rows =
            tables[currentTable];


        window.speechSynthesis.cancel();


        let index = 0;


        function playNext() {

            if (index >= rows.length) {

                return;

            }


            const speech =
                new SpeechSynthesisUtterance(
                    rows[index]
                );


            speech.lang =
                "gu-IN";


            speech.rate =
                0.72;


            speech.pitch =
                1;


            speech.volume =
                1;


            speech.onend =
                function() {

                    index++;

                    setTimeout(
                        playNext,
                        350
                    );

                };


            window.speechSynthesis
                .speak(speech);

        }


        playNext();

    });


/* =========================================================
   DROPDOWN CHANGE
   ========================================================= */

tableSelect.addEventListener(
    "change",
    function() {

        displayTable(
            this.value
        );

    }
);


/* =========================================================
   NEXT TABLE
   ========================================================= */

document
    .getElementById("nextBtn")
    .addEventListener("click", function() {


        const availableTables =
            Object.keys(tables)
                .map(Number)
                .sort(function(a, b) {
                    return a - b;
                });


        const currentIndex =
            availableTables.indexOf(
                currentTable
            );


        if (
            currentIndex <
            availableTables.length - 1
        ) {

            currentTable =
                availableTables[
                    currentIndex + 1
                ];


            tableSelect.value =
                currentTable;


            displayTable(
                currentTable
            );

        }

    });


/* =========================================================
   PREVIOUS TABLE
   ========================================================= */

document
    .getElementById("prevBtn")
    .addEventListener("click", function() {


        const availableTables =
            Object.keys(tables)
                .map(Number)
                .sort(function(a, b) {
                    return a - b;
                });


        const currentIndex =
            availableTables.indexOf(
                currentTable
            );


        if (currentIndex > 0) {

            currentTable =
                availableTables[
                    currentIndex - 1
                ];


            tableSelect.value =
                currentTable;


            displayTable(
                currentTable
            );

        }

    });


/* =========================================================
   RANDOM PRACTICE
   ========================================================= */

document
    .getElementById("randomBtn")
    .addEventListener("click", function() {


        const multiplier =
            Math.floor(
                Math.random() * 10
            ) + 1;


        /*
           હાલ practice માટે
           actual multiplication result
        */

        const answer =
            currentTable *
            multiplier;


        currentQuestion = {

            multiplier:
                multiplier,

            answer:
                answer

        };


        document
            .getElementById("questionBox")
            .textContent =
            `${currentTable} × ${multiplier} = ?`;


        document
            .getElementById("answerBox")
            .textContent = "";


        /* પ્રશ્ન બોલાવવો */

        speakGujarati(
            `${currentTable} ગુણ્યા ${multiplier} કેટલા થાય?`
        );

    });


/* =========================================================
   ANSWER બતાવવો
   ========================================================= */

document
    .getElementById("showAnswerBtn")
    .addEventListener("click", function() {


        if (!currentQuestion) {

            alert(
                "પહેલા Random પ્રશ્ન પસંદ કરો."
            );

            return;

        }


        document
            .getElementById("answerBox")
            .textContent =
            `જવાબ: ${currentQuestion.answer}`;

    });


/* =========================================================
   INITIAL LOAD
   ========================================================= */

loadSelector();

